-- 피부 유형 설문 (근거: Notion "피부 타입 구분 v2", "군 장병용 피부 유형 진단 설문")
-- 이 파일은 docs의 정의로 생성했다. 값을 바꿀 때는 새 마이그레이션을 추가한다.

CREATE TABLE skin_types (
    code         VARCHAR(10)  PRIMARY KEY,
    oil          VARCHAR(20)  NOT NULL,
    sensitivity  VARCHAR(20)  NOT NULL,
    pigmentation VARCHAR(20)  NOT NULL,
    wt           VARCHAR(1)   NOT NULL,
    care_style   VARCHAR(20)  NOT NULL,
    title        VARCHAR(100) NOT NULL,
    sort_order   INT          NOT NULL,
    UNIQUE (oil, sensitivity, pigmentation, wt, care_style)
);

CREATE TABLE skin_tags (
    code  VARCHAR(40)  PRIMARY KEY,
    label VARCHAR(100) NOT NULL,
    trait VARCHAR(30)  NOT NULL
);

CREATE TABLE skin_type_tags (
    skin_type_code VARCHAR(10) NOT NULL REFERENCES skin_types (code),
    tag_code       VARCHAR(40) NOT NULL REFERENCES skin_tags (code),
    sort_order     INT         NOT NULL,
    PRIMARY KEY (skin_type_code, tag_code)
);

CREATE TABLE skin_type_questions (
    id        BIGSERIAL    PRIMARY KEY,
    version   INT          NOT NULL,
    number    INT          NOT NULL,
    axis      VARCHAR(20)  NOT NULL,
    text      VARCHAR(300) NOT NULL,
    is_image  BOOLEAN      NOT NULL,
    sensitive BOOLEAN      NOT NULL,
    UNIQUE (version, number)
);

CREATE TABLE skin_type_question_options (
    question_id     BIGINT       NOT NULL REFERENCES skin_type_questions (id),
    position        INT          NOT NULL CHECK (position BETWEEN 1 AND 4),
    label           VARCHAR(200) NOT NULL,
    score           INT          NOT NULL CHECK (score BETWEEN 1 AND 4),
    environment_tag VARCHAR(100),
    PRIMARY KEY (question_id, position)
);

CREATE TABLE skin_type_assessments (
    id                    BIGSERIAL   PRIMARY KEY,
    user_id               BIGINT      NOT NULL REFERENCES users (id),
    question_version      INT         NOT NULL,
    answers               JSONB       NOT NULL,
    axis_results          JSONB       NOT NULL,
    survey_code           VARCHAR(10) NOT NULL,
    result_type_code      VARCHAR(10) NOT NULL REFERENCES skin_types (code),
    environment_tags      TEXT[]      NOT NULL,
    retest_recommended_at DATE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX skin_type_assessments_user_idx ON skin_type_assessments (user_id, created_at DESC);

